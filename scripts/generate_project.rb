def flag_value(name)
  value = ENV[name].to_s.strip
  return nil if value.empty?
  return true if %w[1 YES yes true].include?(value)
  return false if %w[0 NO no false].include?(value)
  abort "#{name} must be YES or NO (got #{value.inspect})"
end

