/// Reply handler standing in for one script's handler in the app. It answers with the script ID it was built
/// for and the world the message really came from, and records every body it receives.
final class ScriptHandler: NSObject, WKScriptMessageHandlerWithReply, @unchecked Sendable {
    let id: String
    let expectedWorld: WKContentWorld?
    private let lock = NSLock()
    private var bodies: [[String: Any]] = []
    private var store: [String: Any] = [:]

    init(id: String, expectedWorld: WKContentWorld?) {
        self.id = id
        self.expectedWorld = expectedWorld
    }

    var received: [[String: Any]] { lock.lock(); defer { lock.unlock() }; return bodies }
    var values: [String: Any] { lock.lock(); defer { lock.unlock() }; return store }

    func userContentController(_ ucc: WKUserContentController, didReceive message: WKScriptMessage,
                               replyHandler: @escaping (Any?, String?) -> Void) {
        let body = message.body as? [String: Any] ?? ["raw": "\(message.body)"]
        lock.lock()
        bodies.append(body)
        if body["op"] as? String == "set", let k = body["k"] as? String { store[k] = body["v"] }
        lock.unlock()
        replyHandler(["id": id, "world": message.world.name ?? "page",
                      "worldMatches": expectedWorld.map { $0 === message.world } ?? false], nil)
    }
}

final class NavigationWaiter: NSObject, WKNavigationDelegate {
    var continuation: CheckedContinuation<Void, Error>?
    func webView(_ webView: WKWebView, didFinish navigation: WKNavigation!) { finish(nil) }
    func webView(_ webView: WKWebView, didFail navigation: WKNavigation!, withError error: Error) { finish(error) }
    func webView(_ webView: WKWebView, didFailProvisionalNavigation navigation: WKNavigation!, withError error: Error) { finish(error) }
    private func finish(_ error: Error?) {
        guard let c = continuation else { return }
        continuation = nil
        if let error { c.resume(throwing: error) } else { c.resume() }
    }
}

struct Row: Codable {
    let question: String
    let variant: String
    let check: String
    let outcome: String // "yes", "no" or "info"
    let detail: String
}

/// Rows from every test, written once at the end of the run.
enum Results {
    nonisolated(unsafe) static var rows: [Row] = []
    static let lock = NSLock()
    static func add(_ r: Row) { lock.lock(); rows.append(r); lock.unlock() }

    static func write() {
        let dir = ProcessInfo.processInfo.environment["SPIKE_OUT"] ?? NSTemporaryDirectory()
        lock.lock(); let all = rows; lock.unlock()
        let sorted = all.enumerated().sorted { ($0.element.question, $0.offset) < ($1.element.question, $1.offset) }.map(\.element)
        let enc = JSONEncoder()
        enc.outputFormatting = [.prettyPrinted, .sortedKeys]
        try? enc.encode(sorted).write(to: URL(fileURLWithPath: dir + "/results.json"))
        var md = "# M4 script-worlds spike: raw results\n\nGenerated by `m4-spike/run.sh`. \(sorted.count) rows. `yes`/`no` answer the check as worded; `info` is a measurement.\n"
        var q = ""
        for r in sorted {
            if r.question != q {
                q = r.question
                md += "\n## \(q)\n\n| Variant | Check | Result | Detail |\n|---|---|---|---|\n"
            }
            let d = r.detail.replacingOccurrences(of: "|", with: "\\|").replacingOccurrences(of: "\n", with: " ")
            md += "| \(r.variant) | \(r.check) | \(r.outcome) | \(d) |\n"
        }
        try? md.write(toFile: dir + "/results.md", atomically: true, encoding: .utf8)
    }
}

/// Shared plumbing: servers, web views, world helpers.
@MainActor
class SpikeCase: XCTestCase {
    static let agentWorld = WKContentWorld.world(name: "WukongAgent")
    static let worldA = WKContentWorld.world(name: "WukongScript.a")
    static let worldB = WKContentWorld.world(name: "WukongScript.b")

    override class func tearDown() { Results.write(); super.tearDown() }

    var main: SpikeServer!
    var waiter = NavigationWaiter()

    override func setUp() async throws {
        main = try SpikeServer(name: "main") { req in
            switch req.path {
            case "/page":
                let v = Variant.all.first { $0.policy.rawValue == req.query["csp"] && $0.via == req.query["via"] } ?? Variant.all[0]
                var headers: [String: String] = [:]
                if v.via == "header", let csp = v.cspText { headers["Content-Security-Policy"] = csp }
                return .text(Fixtures.page(v), type: "text/html; charset=utf-8", headers: headers)
            case "/page.js": return .text(Fixtures.pageJS, type: "text/javascript")
            case "/page.css": return .text(Fixtures.pageCSS, type: "text/css")
            default: return SpikeServer.Response(status: 404)
            }
        }
        try await main.start()
    }

    override func tearDown() async throws { main.stop() }

    func record(_ q: String, _ v: String, _ check: String, _ outcome: String, _ detail: String) {
        Results.add(Row(question: q, variant: v, check: check, outcome: outcome, detail: detail))
    }

    func yn(_ b: Bool) -> String { b ? "yes" : "no" }

    func hostWindow() async throws -> UIWindow {
        for _ in 0 ..< 50 {
            if let w = UIApplication.shared.connectedScenes.compactMap({ $0 as? UIWindowScene }).flatMap(\.windows).first { return w }
            try await Task.sleep(nanoseconds: 100_000_000)
        }
        throw NSError(domain: "spike", code: 1, userInfo: [NSLocalizedDescriptionKey: "no host window"])
    }

    func makeView(_ setup: @escaping (WKUserContentController) -> Void) async throws -> WKWebView {
        let cfg = WKWebViewConfiguration()
        cfg.websiteDataStore = .nonPersistent()
        setup(cfg.userContentController)
        let wv = WKWebView(frame: CGRect(x: 0, y: 0, width: 390, height: 600), configuration: cfg)
        if #available(iOS 16.4, *) { wv.isInspectable = true }
        wv.navigationDelegate = waiter
        try await hostWindow().addSubview(wv)
        return wv
    }

    func pageURL(_ v: Variant) -> URL { URL(string: "\(main.origin)/page?csp=\(v.policy.rawValue)&via=\(v.via)")! }

    /// Loads the fixture page and waits for `didFinish`. Returns the load time in milliseconds.
    @discardableResult
    func navigate(_ wv: WKWebView, _ v: Variant) async throws -> Double {
        let t0 = Date()
        try await withCheckedThrowingContinuation { (c: CheckedContinuation<Void, Error>) in
            waiter.continuation = c
            wv.load(URLRequest(url: pageURL(v)))
        }
        return Date().timeIntervalSince(t0) * 1000
    }

    func teardown(_ wv: WKWebView) {
        wv.configuration.userContentController.removeAllScriptMessageHandlers()
        wv.removeAllUserScripts()
        wv.removeFromSuperview()
    }

    /// Runs an async function body in a world. The body returns a JSON string; a throw comes back as `{threw: …}`.
    func call(_ wv: WKWebView, _ body: String, in world: WKContentWorld, args: [String: Any] = [:]) async -> [String: Any] {
        let wrapped = """
        try { \(body) } catch (e) { return JSON.stringify({threw: e.name + ': ' + e.message}); }
        """
        do {
            let v = try await wv.callAsyncJavaScript(wrapped, arguments: args, in: nil, contentWorld: world)
            return (try? JSONSerialization.jsonObject(with: Data((v as? String ?? "{}").utf8))) as? [String: Any] ?? ["raw": "\(String(describing: v))"]
        } catch {
            let ns = error as NSError
            return ["swiftError": (ns.userInfo["WKJavaScriptExceptionMessage"] as? String) ?? ns.localizedDescription]
        }
    }

    func pause(_ ms: UInt64) async { try? await Task.sleep(nanoseconds: ms * 1_000_000) }

    func json(_ o: Any) -> String {
        (try? JSONSerialization.data(withJSONObject: o, options: [.sortedKeys, .fragmentsAllowed])).flatMap { String(data: $0, encoding: .utf8) } ?? "?"
    }

    /// Physical footprint of the web view's content process in bytes, or nil when the process can't be read.
    func footprint(_ wv: WKWebView) -> Int? {
        guard let pidNumber = wv.value(forKey: "_webProcessIdentifier") as? NSNumber else { return nil }
        typealias Fn = @convention(c) (Int32, Int32, UnsafeMutableRawPointer) -> Int32
        guard let sym = dlsym(UnsafeMutableRawPointer(bitPattern: -2), "proc_pid_rusage") else { return nil }
        let fn = unsafeBitCast(sym, to: Fn.self)
        let buf = UnsafeMutableRawPointer.allocate(byteCount: 1024, alignment: 8)
        defer { buf.deallocate() }
        guard fn(pidNumber.int32Value, 4, buf) == 0 else { return nil } // RUSAGE_INFO_V4, ri_phys_footprint at offset 72
        return Int(buf.load(fromByteOffset: 72, as: UInt64.self))
    }
}

extension WKWebView {
    func removeAllUserScripts() { configuration.userContentController.removeAllUserScripts() }
}
